export function buildVisualDiffFeedbackSubject(
  items: ScopeItem[],
  meta?: VisualDiffFeedbackMeta,
  lang?: FeedbackLang | string,
): string {
  const t = COPY[normalizeFeedbackLang(lang)]
  const name = (meta?.designName || '').trim()
  const code = (meta?.codePath || '').trim()
  const label = name || code || 'UI'
  const pair = name && code ? `${name} \u2194 ${code}` : label
  const prefix = `[TraceScope]${t.subjectPrefix}`
  if (items.length === 1) {
    return `${prefix}${pair} \u00b7 ${t.subjectOne}${items[0]!.displayName}`.slice(0, 120)
  }
  return `${prefix}${pair} \u00b7 ${items.length}${t.subjectManySuffix}`.slice(0, 120)
}

/** Build markdown body for a batch of UI-review diffs. */
export function buildVisualDiffFeedbackDescription(input: {
  repoPath: string
  items: ScopeItem[]
  meta?: VisualDiffFeedbackMeta
  attachments?: ReportAttachment[]
  embedScreenshotDataUrls?: boolean
  screenshotEmbeds?: Record<string, string>
  lang?: FeedbackLang | string
}): string {
  const t = COPY[normalizeFeedbackLang(input.lang)]
  const meta = input.meta || {}
  const embedDataUrls = input.embedScreenshotDataUrls !== false
  const lines = [
    t.title,
    '',
    `- ${t.repo}: \`${input.repoPath}\``,
  ]
  if (meta.designName?.trim()) lines.push(`- ${t.design}: ${meta.designName.trim()}`)
  if (meta.designUrl?.trim()) lines.push(`- ${t.link}: ${meta.designUrl.trim()}`)
  if (meta.codePath?.trim()) lines.push(`- ${t.code}: \`${meta.codePath.trim()}\``)
  if (meta.platformLabel?.trim()) lines.push(`- ${t.platform}: ${meta.platformLabel.trim()}`)
  lines.push(`- ${t.diffCount}: ${input.items.length}`, '')

  const taskAttachments = input.attachments || []
  if (taskAttachments.length) {
    lines.push(t.attachments, '')
    taskAttachments.forEach((a, i) => {
      const sizeLabel =
        a.size >= 1024 * 1024
          ? `${(a.size / 1024 / 1024).toFixed(1)} MB`
          : `${Math.max(1, Math.round(a.size / 1024))} KB`
      lines.push(`${i + 1}. ${a.name} (${a.mime || 'file'} \u00b7 ${sizeLabel})`)
    })
    lines.push('')
  }

  input.items.forEach((item, i) => {
    lines.push(`### ${i + 1}. ${item.displayName}`, '')
    lines.push(`- ${t.risk}: ${item.risk}`)
    if (item.files?.length) {
      lines.push(`- ${t.files}: ${item.files.map((f) => `\`${f}\``).join(', ')}`)
    }
    const note = item.testerNote?.trim()
    if (note) {
      lines.push(`- ${t.detail}:`)
      for (const line of note.split('\n')) {
        lines.push(`  ${line}`)
      }
    } else {
      lines.push(`- ${t.detail}: ${t.detailEmpty}`)
    }
    const shots = item.testerScreenshots || []
    if (shots.length) {
      lines.push(`- ${t.screenshots} (${shots.length}):`)
      shots.forEach((s, idx) => {
        const embedKey = `${i}:${idx}`
        const embed = input.screenshotEmbeds?.[embedKey]
        if (embed) lines.push(`  ${embed}`)
        else if (embedDataUrls) lines.push(`  ![${s.name}](${s.dataUrl})`)
        else lines.push(`  ${s.name}`)
      })
    }
    if (item.suggestedSteps?.length) {
      lines.push(`- ${t.steps}:`)
      item.suggestedSteps.forEach((s, idx) => lines.push(`  ${idx + 1}. ${s}`))
    }
    lines.push('')
  })

  lines.push('---', t.footer)
  const body = lines.join('\n')
  if (body.length > 180_000 && embedDataUrls) {
    return buildVisualDiffFeedbackDescription({
      ...input,
      embedScreenshotDataUrls: false,
      screenshotEmbeds: undefined,
    })
  }
  return body
}
