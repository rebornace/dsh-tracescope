/**
 * Feedback body for design↔code UI review defects (not impact verification).
 * Chinese copy uses \\u escapes so the source stays ASCII-safe on Windows.
 */
import type { ReportAttachment, ScopeItem } from '../types.js'
import {
  normalizeFeedbackLang,
  type FeedbackLang,
} from './feedback.js'

export type FeedbackKind = 'impact' | 'visual-diff' | 'crash'

export interface VisualDiffFeedbackMeta {
  designName?: string
  designUrl?: string
  codePath?: string
  platformLabel?: string
}

