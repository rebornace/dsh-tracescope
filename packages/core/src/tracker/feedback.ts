/**
 * Shared feedback construction for every tracker adapter.
 *
 * Platform adapters only speak HTTP; how a batch of failed verification items
 * is rendered into a subject / markdown body lives here so the wording and the
 * oversized-body guard stay consistent across providers.
 *
 * Wording follows Host locale (`zh` | `en`); unknown values fall back to `zh`.
 * Chinese copy is stored as \\u escapes so the source stays ASCII-safe on Windows.
 */
import type { ReportAttachment, ScopeItem } from '../types.js'

export type FeedbackLang = 'zh' | 'en'

export function normalizeFeedbackLang(raw: unknown): FeedbackLang {
  if (typeof raw !== 'string') return 'zh'
  const s = raw.trim().toLowerCase()
  if (s === 'en' || s.startsWith('en-') || s.startsWith('en_')) return 'en'
  return 'zh'
}

