export function bufferFromDataUrl(dataUrl: string): Buffer | null {
  const trimmed = dataUrl.trim()
  const m = /^data:([^;,]+)(?:;charset=[^;,]*)?;base64,([\s\S]+)$/i.exec(trimmed)
  if (!m) return null
  try {
    return Buffer.from(m[2]!.replace(/\s+/g, ''), 'base64')
  } catch {
    return null
  }
}

export function safeAttachLabel(name: string): string {
  return (name || 'file').replace(/[<>:"/\\|?*\x00-\x1f]+/g, '_').slice(0, 60)
}

/** Build markdown body for a batch of failed verification items. */
export function buildFailFeedbackDescription(input: {
  repoPath: string
  baseCommit: string
  headCommit: string
  items: ScopeItem[]
  attachments?: ReportAttachment[]
  /**
   * When true (default), embed screenshot data-URLs under each item.
   * Set false when images are uploaded as real attachments instead.
   */
  embedScreenshotDataUrls?: boolean
  /** Optional embed markdown keyed by `itemIndex:shotIndex`. */
  screenshotEmbeds?: Record<string, string>
  /** Host UI language; defaults to Chinese. */
  lang?: FeedbackLang | string
}): string {
  const t = COPY[normalizeFeedbackLang(input.lang)]
  const embedDataUrls = input.embedScreenshotDataUrls !== false
  const lines = [
    t.title,
    '',
    `- ${t.repo}: \`${input.repoPath}\``,
    `- ${t.base}: \`${input.baseCommit}\``,
    `- ${t.head}: \`${input.headCommit}\``,
    `- ${t.failCount}: ${input.items.length}`,
    '',
  ]
  const taskAttachments = input.attachments || []
  if (taskAttachments.length) {
    lines.push(t.attachments, '')
    taskAttachments.forEach((a, i) => {
      const sizeLabel =
        a.size >= 1024 * 1024
          ? `${(a.size / 1024 / 1024).toFixed(1)} MB`
          : `${Math.max(1, Math.round(a.size / 1024))} KB`
      lines.push(`${i + 1}. ${a.name} (${a.mime || 'file'} \u00b7 ${sizeLabel})`)
    })
    lines.push('')
  }
  input.items.forEach((item, i) => {
    lines.push(`### ${i + 1}. ${item.displayName}`)
    lines.push('')
    lines.push(
      `- ${t.kind}: ${item.kind === 'direct' ? t.kindDirect : t.kindRipple}`,
    )
    lines.push(`- ${t.risk}: ${item.risk}`)
    if (item.files?.length) {
      lines.push(`- ${t.files}: ${item.files.map((f) => `\`${f}\``).join(', ')}`)
    }
    lines.push(`- ${t.note}: ${item.testerNote?.trim() || t.noteEmpty}`)
    const shots = item.testerScreenshots || []
    if (shots.length) {
      lines.push(`- ${t.screenshots} (${shots.length}):`)
      shots.forEach((s, idx) => {
        const embedKey = `${i}:${idx}`
        const yunxiaoEmbed = input.screenshotEmbeds?.[embedKey]
        if (yunxiaoEmbed) {
          lines.push(`  ${yunxiaoEmbed}`)
        } else if (embedDataUrls) {
          lines.push(`  ![${s.name}](${s.dataUrl})`)
        } else {
          lines.push(`  ${s.name}`)
        }
      })
    }
    if (item.suggestedSteps?.length) {
      lines.push(`- ${t.steps}:`)
      item.suggestedSteps.forEach((s, idx) => lines.push(`  ${idx + 1}. ${s}`))
    }
    lines.push('')
  })
  lines.push('---')
  lines.push(t.footer)
  const body = lines.join('\n')
  if (body.length > 180_000 && embedDataUrls) {
    return buildFailFeedbackDescription({
      ...input,
      embedScreenshotDataUrls: false,
      screenshotEmbeds: undefined,
    })
  }
  return body
}

export function buildFailFeedbackSubject(
  items: ScopeItem[],
  repoLabel?: string,
  lang?: FeedbackLang | string,
): string {
  const t = COPY[normalizeFeedbackLang(lang)]
  const prefix = repoLabel ? `[TraceScope][${repoLabel}] ` : '[TraceScope] '
  if (items.length === 1) {
    return `${prefix}${t.subjectOne}${items[0]!.displayName}`.slice(0, 120)
  }
  return `${prefix}${t.subjectManyPrefix}${items.length}${t.subjectManySuffix}`.slice(0, 120)
}
