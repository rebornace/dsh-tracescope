/** Fields needed to build tracker defect body/subject for feedbackKind crash. */
export interface CrashFeedbackMeta {
  incident: CrashIncident
  matchedFiles: CrashMatchedFile[]
  summary: string
  fixHints?: string[]
  aiAnalysis?: string
}

export interface CrashReportParts {
  repoPath: string
  summary: string
  matchedFiles: CrashMatchedFile[]
  fixHints: string[]
  stackText: string
  incident: CrashIncident
  /** When set, prompt instructs the agent to publish via tool write-back. */
  jobId?: string
}

function formatMatchedFiles(files: CrashMatchedFile[], lang: FeedbackLang): string {
  const t = COPY[lang]
  if (!files.length) return t.noMatch
  return files
    .map((f, i) => {
      const sym = f.symbol ? ` (${f.symbol})` : ''
      return `${i + 1}. \`${f.path}\`${sym} — ${f.reason}`
    })
    .join('\n')
}

function formatFixHints(hints: string[], lang: FeedbackLang): string {
  const t = COPY[lang]
  if (!hints.length) return ''
  return [`${t.fixHints}:`, ...hints.map((h, i) => `${i + 1}. ${h}`)].join('\n')
}

function promptHeader(incident: CrashIncident, exceptionName: string, lang: FeedbackLang): string {
  const t = COPY[lang]
  const parts = [`[${t.promptTitle}]`, exceptionName]
  if (incident.appVersion?.trim()) parts.push(incident.appVersion.trim())
  if (incident.count != null && Number.isFinite(incident.count)) {
    parts.push(`${t.count} ${incident.count}`)
  }
  return parts.join(' \u00b7 ')
}

/** Build DSH composer starter prompt for crash analysis. */
export function buildCrashPrompt(parts: CrashReportParts, lang?: FeedbackLang | string): string {
  const l = normalizeFeedbackLang(lang)
  const t = COPY[l]
  const exceptionName = resolveExceptionName(parts.incident, { stackText: parts.stackText })
  const jobId = parts.jobId?.trim()
  const lines = [
    promptHeader(parts.incident, exceptionName, l),
    ...(jobId
      ? [
          `${t.jobIdLabel}\uff1a${jobId}`,
          `Skill\uff1a${t.skillName}`,
          `${t.publishTool}`,
        ]
      : []),
    `${t.repo}\uff1a${parts.repoPath}`,
    `${t.summary}\uff1a${parts.summary}`,
    `${t.matchedFiles}\uff1a`,
    formatMatchedFiles(parts.matchedFiles, l),
  ]
  const hintsBlock = formatFixHints(parts.fixHints, l)
  if (hintsBlock) {
    lines.push('', hintsBlock)
  }
  lines.push('', `${t.fullStack}\uff1a`, parts.stackText.trim(), '', t.askFix)
  if (jobId) {
    lines.push('', t.publishHint)
  }
  return lines.join('\n')
}

const MAX_DEFECT_STACK_CHARS = 12_000

function appendMetaLine(lines: string[], label: string, value: string | number | undefined): void {
  if (value === undefined || value === null || value === '') return
  lines.push(`- ${label}: ${value}`)
}

/** Build markdown defect body for tracker submit (feedbackKind: crash). */
export function buildCrashDefectBody(input: {
  incident: CrashIncident
  matchedFiles: CrashMatchedFile[]
  summary: string
  fixHints?: string[]
  repoPath?: string
  lang?: FeedbackLang | string
  aiAnalysis?: string
}): string {
  const l = normalizeFeedbackLang(input.lang)
  const t = COPY[l]
  const incident = input.incident
  const stackRaw = incident.stackText.trim()
  const stack =
    stackRaw.length > MAX_DEFECT_STACK_CHARS
      ? `${stackRaw.slice(0, MAX_DEFECT_STACK_CHARS)}\n\u2026`
      : stackRaw

  const lines = [t.defectTitle, '']
  appendMetaLine(lines, t.incident, incident.title)
  appendMetaLine(lines, t.exception, resolveExceptionName(incident, { stackText: stackRaw }))
  appendMetaLine(lines, t.appVersion, incident.appVersion)
  appendMetaLine(lines, t.buildNumber, incident.buildNumber)
  appendMetaLine(lines, t.platform, incident.platform)
  appendMetaLine(lines, t.errorKind, incident.errorKind)
  appendMetaLine(lines, t.status, incident.status)
  appendMetaLine(lines, t.count, incident.count)
  appendMetaLine(lines, t.affectedUsers, incident.affectedUsers)
  appendMetaLine(lines, t.osVersion, incident.osVersion)
  appendMetaLine(lines, t.deviceModel, incident.deviceModel)
  appendMetaLine(lines, t.occurredAt, incident.occurredAt)
  appendMetaLine(lines, t.consoleLink, incident.rawRef)
  if (input.repoPath?.trim()) {
    appendMetaLine(lines, t.repo, input.repoPath.trim())
  }
  lines.push('', `- ${t.summary}: ${input.summary}`, '')
  lines.push(`### ${t.matchedFiles}`, '', formatMatchedFiles(input.matchedFiles, l), '')
  const hints = input.fixHints ?? []
  if (hints.length) {
    lines.push(formatFixHints(hints, l), '')
  }
  const ai = input.aiAnalysis?.trim()
  if (ai) {
    lines.push(`### ${t.aiAnalysis}`, '', ai, '')
  }
  lines.push(`### ${t.stack}`, '', '```', stack, '```', '', '---', t.footer)
  return lines.join('\n')
}

/** Merge a pasted AI reply into an existing analysis report (updates defectBody). */
export function applyAiAnalysisToReport(
  report: {
    incident: CrashIncident
    matchedFiles: CrashMatchedFile[]
    summary: string
    fixHints?: string[]
    prompt: string
    defectBody: string
    aiAnalysis?: string
  },
  aiAnalysis: string,
  options?: { repoPath?: string; lang?: FeedbackLang | string },
): typeof report & { aiAnalysis: string; defectBody: string } {
  const text = aiAnalysis.trim()
  return {
    ...report,
    aiAnalysis: text,
    defectBody: buildCrashDefectBody({
      incident: report.incident,
      matchedFiles: report.matchedFiles,
      summary: report.summary,
      fixHints: report.fixHints,
      repoPath: options?.repoPath,
      lang: options?.lang,
      aiAnalysis: text,
    }),
  }
}

export function buildCrashDefectSubject(incident: CrashIncident, lang?: FeedbackLang | string): string {
  const t = COPY[normalizeFeedbackLang(lang)]
  const title = incident.title.trim() || incident.exceptionName?.trim() || 'Crash'
  return `${t.subjectPrefix} ${title}`.slice(0, 120)
}

function firstNonEmptyMarkdownTitleLine(markdown: string): string {
  for (const line of markdown.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed) continue
    return trimmed.replace(/^#+\s*/, '').trim() || trimmed
  }
  return 'Crash'
}

/** Tracker subject for feedbackKind crash (never impact verification wording). */
export function buildCrashFeedbackSubject(input: {
  lang?: FeedbackLang | string
  crashMeta?: CrashFeedbackMeta
  prebuiltDescription?: string
}): string {
  const l = normalizeFeedbackLang(input.lang)
  const t = COPY[l]
  if (input.crashMeta) {
    return buildCrashDefectSubject(input.crashMeta.incident, l)
  }
  const prebuilt = input.prebuiltDescription?.trim()
  if (prebuilt) {
    const title = firstNonEmptyMarkdownTitleLine(prebuilt)
    return `${t.subjectPrefix} ${title}`.slice(0, 120)
  }
  return `${t.subjectPrefix} Crash`.slice(0, 120)
}

export function crashSummaryNoMatchLabel(lang?: FeedbackLang | string): string {
  return COPY[normalizeFeedbackLang(lang)].summaryNoMatch
}
